function translateStaticText() {
  document.documentElement.lang = currentLanguage === "zh" ? "zh-Hans" : "en";
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.getAttribute("data-i18n");
    const value = translations[currentLanguage][key];
    if (value) {
      element.textContent = value;
    }
  });
  if (languageToggle) {
    languageToggle.textContent = currentLanguage === "zh" ? "EN" : "中文";
    languageToggle.setAttribute("aria-label", currentLanguage === "zh" ? "Switch to English" : "切换至中文");
  }
  updateMenuLabel();
  updateImageLabels();
}

function renderCollections() {
  if (!collectionList) {
    return;
  }
  const focusedIndex = document.activeElement?.dataset.collectionIndex;
  collectionList.innerHTML = "";
  collectionItems.forEach((item, index) => {
    const card = document.createElement("button");
    card.className = `collection-card${index === selectedCollectionIndex ? " is-active" : ""}`;
    card.type = "button";
    card.dataset.collectionIndex = String(index);
    card.setAttribute("aria-pressed", String(index === selectedCollectionIndex));

    const img = document.createElement("img");
    img.src = item.image;
    img.alt = item.title[currentLanguage];
    img.loading = "eager";
    img.decoding = "async";
    if (item.fit === "contain") {
      img.classList.add("image--contain");
    }

    const copy = document.createElement("div");
    copy.className = "collection-card__copy";

    const type = document.createElement("span");
    type.textContent = item.type[currentLanguage];

    const title = document.createElement("h3");
    title.textContent = item.title[currentLanguage];

    const summary = document.createElement("p");
    summary.textContent = item.summary[currentLanguage];

    copy.append(title, type, summary);
    card.append(img, copy);
    card.addEventListener("click", () => {
      selectedCollectionIndex = index;
      updateCollectionDetail();
      collectionList.querySelectorAll(".collection-card").forEach((element, position) => {
        element.classList.toggle("is-active", position === index);
        element.setAttribute("aria-pressed", String(position === index));
      });
      document.querySelector("[data-collection-detail]").scrollIntoView({
        behavior: matchMedia("(prefers-reduced-motion: reduce)").matches ? "instant" : "smooth",
        block: "start"
      });
    });
    collectionList.appendChild(card);
  });
  if (focusedIndex !== undefined) {
    collectionList.querySelector(`[data-collection-index="${focusedIndex}"]`)?.focus({ preventScroll: true });
  }
}

function updateCollectionDetail() {
  if (!detail.image || !detail.type || !detail.title || !detail.description || !detail.date || !detail.place) {
    return;
  }
  const item = collectionItems[selectedCollectionIndex];
  detail.image.src = item.image;
  detail.image.alt = item.title[currentLanguage];
  detail.image.classList.toggle("image--contain", item.fit === "contain");
  detail.type.textContent = item.type[currentLanguage];
  detail.title.textContent = item.title[currentLanguage];
  detail.description.textContent = item.summary[currentLanguage];
  detail.date.textContent = item.date[currentLanguage];
  detail.place.textContent = item.place[currentLanguage];
  updateImageLabels();
}

function updateLanguage() {
  translateStaticText();
  updateCollectionDetail();
  renderCollections();
}

